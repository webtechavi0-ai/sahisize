#!/usr/bin/env node
/**
 * Copies the codec .wasm binaries from node_modules into public/wasm with a content hash in the
 * file name (`jpeg-enc.<sha8>.wasm`) and writes src/engine/wasm-manifest.generated.ts, which maps
 * each codec name to its hashed URL.
 *
 * Why hashed: the JS glue (bundled by Next under /_next/static, already hashed) and the .wasm
 * binary must always come from the same package version. With stable names a browser or service
 * worker cache could pair new glue with an old binary. Hashed URLs are immutable, so they can be
 * cached forever (cache-first in public/sw.js) and never mismatch.
 *
 * Runs from package.json (`postinstall`, `dev`, `build`). Idempotent; removes stale hashed files.
 * Usage: node scripts/copy-wasm.mjs [--check]   (--check: exit 1 when the manifest is out of date)
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'public', 'wasm');
const MANIFEST = join(ROOT, 'src', 'engine', 'wasm-manifest.generated.ts');
const PUBLIC_PREFIX = '/wasm/';

/** Codec name -> path inside node_modules. Keep in sync with `WasmName` in src/engine/codecs/codecs.ts. */
const FILES = {
  'jpeg-enc': '@jsquash/jpeg/codec/enc/mozjpeg_enc.wasm',
  'jpeg-dec': '@jsquash/jpeg/codec/dec/mozjpeg_dec.wasm',
  png: '@jsquash/png/codec/pkg/squoosh_png_bg.wasm',
  'webp-enc': '@jsquash/webp/codec/enc/webp_enc.wasm',
  'webp-dec': '@jsquash/webp/codec/dec/webp_dec.wasm',
  resize: '@jsquash/resize/lib/resize/pkg/squoosh_resize_bg.wasm',
};

const checkOnly = process.argv.includes('--check');

const missing = Object.entries(FILES).filter(([, rel]) => !existsSync(join(ROOT, 'node_modules', rel)));
if (missing.length) {
  console.error('[copy-wasm] Missing codec binaries in node_modules:');
  for (const [name, rel] of missing) console.error(`  - ${name}: node_modules/${rel}`);
  console.error('[copy-wasm] Run `npm ci` (or check the @jsquash/* versions in package.json).');
  process.exit(1);
}

/** @type {Record<string, { file: string; src: string; bytes: number }>} */
const entries = {};
for (const [name, rel] of Object.entries(FILES)) {
  const src = join(ROOT, 'node_modules', rel);
  const buf = readFileSync(src);
  const hash = createHash('sha256').update(buf).digest('hex').slice(0, 8);
  entries[name] = { file: `${name}.${hash}.wasm`, src, bytes: buf.length };
}

const names = Object.keys(entries).sort();
const manifest = `/**
 * GENERATED by scripts/copy-wasm.mjs. Do not edit by hand.
 * Content-hashed URLs of the codec binaries copied to public/wasm. Deterministic for a given
 * lockfile, so it is safe to commit; it is rewritten on every install/dev/build.
 */
export const WASM_MANIFEST = {
${names.map((n) => `  '${n}': '${PUBLIC_PREFIX}${entries[n].file}',`).join('\n')}
} as const;

export type WasmManifestName = keyof typeof WASM_MANIFEST;
`;

if (checkOnly) {
  const current = existsSync(MANIFEST) ? readFileSync(MANIFEST, 'utf8') : '';
  const filesOk = names.every((n) => existsSync(join(OUT_DIR, entries[n].file)));
  if (current !== manifest || !filesOk) {
    console.error('[copy-wasm] wasm manifest or public/wasm is out of date: run node scripts/copy-wasm.mjs');
    process.exit(1);
  }
  console.log('[copy-wasm] up to date');
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
const keep = new Set(names.map((n) => entries[n].file));
for (const f of readdirSync(OUT_DIR)) {
  if (f.endsWith('.wasm') && !keep.has(f)) rmSync(join(OUT_DIR, f));
}
for (const n of names) {
  const dest = join(OUT_DIR, entries[n].file);
  if (!existsSync(dest)) copyFileSync(entries[n].src, dest);
}
const prev = existsSync(MANIFEST) ? readFileSync(MANIFEST, 'utf8') : '';
if (prev !== manifest) writeFileSync(MANIFEST, manifest);
console.log(`[copy-wasm] ${names.length} codecs -> public/wasm (${names.map((n) => entries[n].file).join(', ')})`);
